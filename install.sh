#!/usr/bin/env bash
#
# install.sh — install jira-cli-manager for the current user.
#
# Does no sudo and writes nothing outside $HOME and this repository.
# Safe to run repeatedly: it upgrades the install and never overwrites an
# existing environment file.
#
#   ./install.sh                  install or upgrade
#   ./install.sh --import-legacy  also migrate ~/.jira-cli/config.env (1.x)
#   ./install.sh --uninstall      remove the launchers only (keeps .env)
#   ./install.sh --force          replace/remove ~/.local/bin/{jira,jira-cli,jira-mcp}
#                                 even when another program owns them, and use a
#                                 non-empty JIRA_CONFIG_DIR that holds no jira-cli files
#   ./install.sh --help
#
set -euo pipefail

REPO_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
VENV_DIR="$REPO_DIR/.venv"
CONFIG_DIR="${JIRA_CONFIG_DIR:-${HOME:-}/.config/jira-cli}"
ENV_TEMPLATE="$REPO_DIR/.env.example"
LAUNCHERS=("jira" "jira-cli" "jira-mcp")
# Second line of every launcher this script writes. A file in ~/.local/bin
# with one of the launcher names but without this line belongs to another
# program (several Jira CLIs install a `jira` binary) and is never touched
# without --force.
LAUNCHER_MARKER="# Generated by jira-cli-manager install.sh. Safe to delete."

IMPORT_LEGACY=0
DO_UNINSTALL=0
FORCE=0

say()  { printf '%s\n' "$*"; }
step() { printf '==> %s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

usage() {
    awk 'NR >= 3 && /^#/ { sub(/^# ?/, ""); print; next } NR >= 3 { exit }' "${BASH_SOURCE[0]}"
}

parse_args() {
    while [ "$#" -gt 0 ]; do
        case "$1" in
            --import-legacy) IMPORT_LEGACY=1 ;;
            --uninstall)     DO_UNINSTALL=1 ;;
            --force)         FORCE=1 ;;
            -h|--help)       usage; exit 0 ;;
            *)               die "unknown option: $1 (try --help)" ;;
        esac
        shift
    done
}

# --- path safety -------------------------------------------------------------
# HOME decides where the launchers go; an empty or relative HOME would put
# them (and the default config dir) somewhere the user did not mean.
check_home() {
    case "${HOME:-}" in
        /?*) ;;
        *) die "HOME must be set to an absolute path other than / (got '${HOME:-}')" ;;
    esac
}

# Print PATH with repeated slashes squeezed and trailing slashes removed.
normalize_path() {
    local p
    p="$(printf '%s' "$1" | tr -s '/')"
    while [ "${#p}" -gt 1 ] && [ "${p%/}" != "$p" ]; do
        p="${p%/}"
    done
    printf '%s' "$p"
}

# Print the symlink-resolved form of PATH when realpath can do it, otherwise
# PATH itself.
resolve_path() {
    local r
    if r="$(realpath -m -- "$1" 2>/dev/null)" && [ -n "$r" ]; then
        printf '%s' "$r"
    else
        printf '%s' "$1"
    fi
}

# Succeed when PATH must never be used as the config directory: the root, the
# home directory or any of its ancestors, or an operating-system directory.
is_forbidden_dir() {
    local p="$1" home
    home="$(normalize_path "$HOME")"
    [ "$p" = "/" ] && return 0
    [ "$p" = "$home" ] && return 0
    [ "$p" = "$(resolve_path "$home")" ] && return 0
    case "$home/" in "$p"/*) return 0 ;; esac
    case "$p" in
        /bin|/boot|/dev|/etc|/home|/lib|/lib32|/lib64|/libx32|/media|/mnt|/opt|/proc|/root|/run|/sbin|/snap|/srv|/sys|/tmp|/usr|/var|/var/tmp)
            return 0 ;;
        /Applications|/Library|/System|/Users|/Volumes|/private|/private/tmp|/private/var)
            return 0 ;;
        /bin/*|/boot/*|/dev/*|/etc/*|/lib/*|/lib32/*|/lib64/*|/libx32/*|/proc/*|/run/*|/sbin/*|/sys/*|/usr/*|/System/*)
            return 0 ;;
    esac
    return 1
}

# Succeed when DIR already holds something only jira-cli would have put there.
looks_like_config_dir() {
    local dir="$1" f
    for f in .env teams.yaml filters.yaml plans; do
        [ -e "$dir/$f" ] && return 0
    done
    return 1
}

# JIRA_CONFIG_DIR is chmodded 700 by this script and named in the "delete it
# yourself" advice of the uninstaller, so a mistaken value (JIRA_CONFIG_DIR=$HOME,
# a shared directory, a relative path) must be refused, not acted on.
validate_config_dir() {
    local dir="$CONFIG_DIR"
    case "$dir" in
        *$'\n'*) die "JIRA_CONFIG_DIR must not contain a newline" ;;
        /*) ;;
        *) die "JIRA_CONFIG_DIR must be an absolute path (got '$dir')" ;;
    esac
    case "/$dir/" in
        */../*|*/./*) die "JIRA_CONFIG_DIR must not contain '.' or '..' components (got '$dir')" ;;
    esac
    dir="$(normalize_path "$dir")"
    if is_forbidden_dir "$dir" || is_forbidden_dir "$(resolve_path "$dir")"; then
        die "refusing JIRA_CONFIG_DIR='$dir': it is /, your home directory (or above it), or a system directory. Point it at a dedicated directory such as \$HOME/.config/jira-cli."
    fi
    if [ -e "$dir" ] && [ ! -d "$dir" ]; then
        die "JIRA_CONFIG_DIR='$dir' exists and is not a directory"
    fi
    CONFIG_DIR="$dir"
}

# Install only: never chmod 700 a populated directory that is not ours.
check_config_dir_is_ours() {
    [ -d "$CONFIG_DIR" ] || return 0
    [ -n "$(ls -A -- "$CONFIG_DIR" 2>/dev/null)" ] || return 0
    looks_like_config_dir "$CONFIG_DIR" && return 0
    if [ "$FORCE" -eq 1 ]; then
        warn "--force: using non-empty $CONFIG_DIR although it holds no jira-cli files"
        return 0
    fi
    die "refusing JIRA_CONFIG_DIR='$CONFIG_DIR': it is not empty and holds no .env, teams.yaml, filters.yaml or plans/, so it does not look like a jira-cli config directory (it would be chmodded 700). Use an empty or new directory, or pass --force."
}

# --- launcher ownership ----------------------------------------------------
# Prints "absent", "ours" or "foreign". A symlink is always foreign: this
# script only ever writes regular files.
launcher_state() {
    local path="$1"
    if [ -L "$path" ]; then
        printf 'foreign'
    elif [ ! -e "$path" ]; then
        printf 'absent'
    elif [ -f "$path" ] \
        && [ "$(head -c 4096 "$path" 2>/dev/null | tr -d '\000' | sed -n '2p')" = "$LAUNCHER_MARKER" ]; then
        printf 'ours'
    else
        printf 'foreign'
    fi
}

# Refuse, before changing anything, when a launcher name is taken by another
# program. With --force, warn and carry on.
check_launchers_are_ours() {
    local action="$1" name path foreign=()
    for name in "${LAUNCHERS[@]}"; do
        path="$BIN_DIR/$name"
        if [ "$(launcher_state "$path")" = "foreign" ]; then
            foreign+=("$path")
        fi
    done
    [ "${#foreign[@]}" -eq 0 ] && return 0
    if [ "$FORCE" -eq 1 ]; then
        warn "--force: will $action files not written by this installer: ${foreign[*]}"
        return 0
    fi
    for path in "${foreign[@]}"; do
        warn "$path was not written by jira-cli-manager (no '$LAUNCHER_MARKER' line)"
    done
    die "refusing to $action ${foreign[*]}; it belongs to another program. Move it aside, or re-run with --force."
}

# --- launcher removal ------------------------------------------------------
# Deliberately narrow: launchers only. The environment file holds the user's
# credential and is never touched by an uninstall.
remove_launchers() {
    local name path state removed=0
    check_launchers_are_ours "remove"
    for name in "${LAUNCHERS[@]}"; do
        path="$BIN_DIR/$name"
        state="$(launcher_state "$path")"
        if [ "$state" = "ours" ] || { [ "$state" = "foreign" ] && [ "$FORCE" -eq 1 ]; }; then
            rm -f -- "$path"
            say "removed $path"
            removed=1
        fi
    done
    [ "$removed" -eq 1 ] || say "no launchers found in $BIN_DIR"
    say ""
    say "Kept, on purpose:"
    say "  $ENV_FILE         (your credential)"
    say "  $CONFIG_DIR/      (teams.yaml, filters.yaml)"
    say "  $VENV_DIR         (delete it by hand if you want the space back)"
}

# --- virtualenv ------------------------------------------------------------
ensure_venv() {
    if [ -x "$VENV_DIR/bin/python" ]; then
        step "using existing virtualenv at $VENV_DIR"
        return
    fi
    step "creating virtualenv at $VENV_DIR"
    local py
    py="$(command -v python3 || true)"
    [ -n "$py" ] || die "python3 not found on PATH"
    "$py" -m venv -- "$VENV_DIR"
    [ -x "$VENV_DIR/bin/python" ] || die "virtualenv creation failed: no $VENV_DIR/bin/python"
}

install_package() {
    step "installing jira-cli-manager into the virtualenv"
    "$VENV_DIR/bin/python" -m pip install --quiet --upgrade pip
    "$VENV_DIR/bin/python" -m pip install --quiet --editable "$REPO_DIR"
}

# --- configuration ---------------------------------------------------------
ensure_config_dir() {
    step "preparing $CONFIG_DIR"
    mkdir -p -- "$CONFIG_DIR"
    chmod 700 -- "$CONFIG_DIR"
}

ensure_env_file() {
    if [ -e "$ENV_FILE" ]; then
        step "keeping existing $ENV_FILE (not overwritten)"
        chmod 600 -- "$ENV_FILE"
        return
    fi
    [ -f "$ENV_TEMPLATE" ] || die "template not found: $ENV_TEMPLATE"
    step "creating $ENV_FILE from .env.example"
    cp -- "$ENV_TEMPLATE" "$ENV_FILE"
    chmod 600 -- "$ENV_FILE"
}

# Migrate 1.x keys into the new env file. Values are copied through a Python
# helper that reads and writes files only — no value is ever echoed, logged or
# passed on a command line.
import_legacy() {
    if [ ! -f "$LEGACY_CONFIG" ]; then
        warn "--import-legacy: no legacy config at $LEGACY_CONFIG, nothing to import"
        return
    fi
    step "importing keys from the 1.x config (values are not printed)"
    LEGACY_CONFIG="$LEGACY_CONFIG" ENV_FILE="$ENV_FILE" \
        "$VENV_DIR/bin/python" - <<'PY'
import os
import re
from pathlib import Path

LINE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$")
# 1.x names on the left, 2.x names on the right.
ALIASES = {
    "JIRA_EMAIL": "JIRA_USERNAME",
    "JIRA_API_TOKEN": "JIRA_PASSWORD",
    "JIRA_PROJECT": "JIRA_DEFAULT_PROJECT",
}
KNOWN = {
    "JIRA_BASE_URL", "JIRA_AUTH_MODE", "JIRA_PAT", "JIRA_USERNAME", "JIRA_PASSWORD",
    "JIRA_DEFAULT_PROJECT", "JIRA_VERIFY_TLS", "JIRA_TIMEOUT", "JIRA_READ_ONLY",
    "JIRA_HOURS_PER_DAY", "JIRA_DAYS_PER_WEEK", "JIRA_CONFIG_DIR",
    "JIRA_FIELD_SPRINT", "JIRA_FIELD_EPIC_LINK", "JIRA_FIELD_EPIC_NAME",
    "JIRA_FIELD_STORY_POINTS",
}


def unquote(raw: str) -> str:
    raw = raw.split(" #", 1)[0].strip() if not raw.startswith(("'", '"')) else raw
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
        return raw[1:-1]
    return raw


def parse(path: Path) -> dict[str, str]:
    found: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            continue
        key, value = ALIASES.get(m.group(1), m.group(1)), unquote(m.group(2))
        if key in KNOWN and value:
            found.setdefault(key, value)
    return found


legacy_path = Path(os.environ["LEGACY_CONFIG"])
env_path = Path(os.environ["ENV_FILE"])
legacy = parse(legacy_path)
if not legacy:
    print("  no recognised keys in the legacy config")
    raise SystemExit(0)

existing = parse(env_path) if env_path.exists() else {}
lines = env_path.read_text(encoding="utf-8").splitlines() if env_path.exists() else []

# A PAT in the legacy file was stored under the basic-auth name; if the import
# brings a password and no PAT, make the auth mode explicit rather than guessed.
added, skipped = [], []
for key, value in legacy.items():
    if key in existing:
        skipped.append(key)
        continue
    lines.append(f"{key}={value}")
    added.append(key)

if added and "JIRA_AUTH_MODE" not in existing and "JIRA_AUTH_MODE" not in added:
    mode = "pat" if "JIRA_PAT" in legacy else "basic"
    lines.append(f"JIRA_AUTH_MODE={mode}")
    added.append("JIRA_AUTH_MODE")

if added:
    header = f"\n# --- imported from {legacy_path} ---"
    body = lines[: len(lines) - len(added)] + [header] + lines[len(lines) - len(added) :]
    env_path.write_text("\n".join(body) + "\n", encoding="utf-8")
    env_path.chmod(0o600)

print(f"  imported keys: {', '.join(sorted(added)) or 'none'}")
if skipped:
    print(f"  already set, left alone: {', '.join(sorted(skipped))}")
print("  (values were not displayed)")
PY
    chmod 600 -- "$ENV_FILE"
}

# --- launchers -------------------------------------------------------------
# Each launcher is written to a temporary file in BIN_DIR and renamed into
# place: the rename replaces a symlink itself instead of writing through it.
# The target path is shell-quoted with %q, so a repository path containing
# quotes, `$` or backticks cannot break or inject into the launcher.
write_launchers() {
    step "writing launchers into $BIN_DIR"
    mkdir -p -- "$BIN_DIR"
    check_launchers_are_ours "replace"
    local name target tmp
    for name in "${LAUNCHERS[@]}"; do
        target="$VENV_DIR/bin/$name"
        [ -x "$target" ] || die "entry point missing after install: $target"
        tmp="$(mktemp "$BIN_DIR/.$name.XXXXXX")"
        {
            printf '%s\n' '#!/usr/bin/env bash' "$LAUNCHER_MARKER" 'set -euo pipefail'
            printf 'exec %q "$@"\n' "$target"
        } > "$tmp"
        chmod 755 -- "$tmp"
        mv -f -- "$tmp" "$BIN_DIR/$name"
        say "  $BIN_DIR/$name -> $target"
    done
}

check_path() {
    case ":${PATH:-}:" in
        *":$BIN_DIR:"*) return 0 ;;
    esac
    warn "$BIN_DIR is not on your PATH, so 'jira' will not be found yet."
    warn "Add this to your shell profile (~/.bashrc or ~/.zshrc) and reopen the shell:"
    warn "    export PATH=\"\$HOME/.local/bin:\$PATH\""
}

main() {
    parse_args "$@"

    # Validate every path before anything is created, installed or removed.
    check_home
    BIN_DIR="$HOME/.local/bin"
    LEGACY_CONFIG="$HOME/.jira-cli/config.env"
    validate_config_dir
    ENV_FILE="$CONFIG_DIR/.env"

    if [ "$DO_UNINSTALL" -eq 1 ]; then
        step "removing launchers"
        remove_launchers
        exit 0
    fi

    check_config_dir_is_ours
    check_launchers_are_ours "replace"

    ensure_venv
    install_package

    # Everything created while the credential is being handled is private
    # from birth: no window where the env file exists with group/world read
    # before the chmod below lands. The caller's umask is restored afterwards
    # so the launchers keep their normal 755 mode.
    local saved_umask
    saved_umask="$(umask)"
    umask 077
    ensure_config_dir
    ensure_env_file
    if [ "$IMPORT_LEGACY" -eq 1 ]; then
        import_legacy
    fi
    umask "$saved_umask"

    write_launchers
    check_path

    say ""
    say "Installed. Next:"
    say "  1. edit $ENV_FILE  (JIRA_BASE_URL and a Personal Access Token)"
    say "  2. jira doctor"
    say ""
    say "Creating a PAT: avatar -> Profile -> Personal Access Tokens -> Create token."
    say "See README.md for the walkthrough and docs/COMMANDS.md for every command."
}

main "$@"
