"""Installer, packaging and CI hardening.

The shell tests run copies of install.sh / uninstall.sh with HOME and
JIRA_CONFIG_DIR pointed at pytest's tmp_path, never the real home. A fake
``python3`` first on PATH records that it was called and fails, so an install
that got past its safety checks stops at virtualenv creation instead of
touching the network; the sentinel file tells the test how far it got.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parent.parent
MARKER = "# Generated by jira-cli-manager install.sh. Safe to delete."
LAUNCHERS = ("jira", "jira-cli", "jira-mcp")
BASH = shutil.which("bash")

needs_bash = pytest.mark.skipif(BASH is None or sys.platform.startswith("win"), reason="needs a POSIX bash")


# --- packaging / CI (static) -------------------------------------------------


def test_manifest_prunes_tests_and_scripts_from_sdist():
    manifest = REPO / "MANIFEST.in"
    assert manifest.is_file(), "MANIFEST.in is missing: setuptools ships a partial tests/ in the sdist"
    directives = {
        tuple(line.split())
        for line in manifest.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    }
    assert ("prune", "tests") in directives
    assert ("prune", "scripts") in directives


def _ci_jobs() -> dict:
    data = yaml.safe_load((REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8"))
    return data["jobs"]


def test_ci_checkout_does_not_persist_credentials():
    checkouts = [
        (job, step)
        for job, spec in _ci_jobs().items()
        for step in spec.get("steps", [])
        if str(step.get("uses", "")).startswith("actions/checkout@")
    ]
    assert checkouts, "no checkout step found"
    for job, step in checkouts:
        assert (step.get("with") or {}).get("persist-credentials") is False, job


def test_ci_jobs_have_timeouts():
    for job, spec in _ci_jobs().items():
        timeout = spec.get("timeout-minutes")
        assert isinstance(timeout, int) and 0 < timeout <= 60, job


# --- shell harness -------------------------------------------------------------


@pytest.fixture
def sandbox(tmp_path: Path) -> dict:
    home = tmp_path / "home"
    (home / ".local" / "bin").mkdir(parents=True)
    repo = tmp_path / "repo"
    repo.mkdir()
    for name in ("install.sh", "uninstall.sh"):
        shutil.copy2(REPO / name, repo / name)
    fakebin = tmp_path / "fakebin"
    fakebin.mkdir()
    sentinel = tmp_path / "python3-called"
    fake = fakebin / "python3"
    fake.write_text(f"#!/bin/sh\n: > '{sentinel}'\nexit 97\n", encoding="utf-8")
    fake.chmod(0o755)
    return {
        "tmp": tmp_path,
        "home": home,
        "bin": home / ".local" / "bin",
        "repo": repo,
        "fakebin": fakebin,
        "sentinel": sentinel,
    }


def run(sb: dict, script: str, *args: str, config_dir: str | None = None) -> subprocess.CompletedProcess:
    env = {"HOME": str(sb["home"]), "PATH": f"{sb['fakebin']}:/usr/bin:/bin", "LC_ALL": "C"}
    if config_dir is not None:
        env["JIRA_CONFIG_DIR"] = config_dir
    return subprocess.run(  # noqa: S603 - fixed argv, no shell, sandboxed HOME
        [BASH, str(sb["repo"] / script), *args],
        env=env,
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )


def write_ours(path: Path) -> None:
    path.write_text(
        f'#!/usr/bin/env bash\n{MARKER}\nset -euo pipefail\nexec /x/.venv/bin/jira "$@"\n', encoding="utf-8"
    )
    path.chmod(0o755)


FOREIGN = '#!/bin/sh\n# some other jira client\nexec /opt/other/jira "$@"\n'


# --- launchers owned by another program ----------------------------------------


@needs_bash
def test_uninstall_refuses_foreign_launcher_and_removes_nothing(sandbox):
    foreign = sandbox["bin"] / "jira"
    foreign.write_text(FOREIGN, encoding="utf-8")
    write_ours(sandbox["bin"] / "jira-mcp")
    res = run(sandbox, "uninstall.sh")
    assert res.returncode != 0
    assert "refusing to remove" in res.stderr and str(foreign) in res.stderr
    assert foreign.read_text(encoding="utf-8") == FOREIGN
    assert (sandbox["bin"] / "jira-mcp").exists(), "refusal must leave every launcher in place"


@needs_bash
def test_uninstall_removes_only_own_launchers(sandbox):
    for name in LAUNCHERS:
        write_ours(sandbox["bin"] / name)
    keep = sandbox["bin"] / "jira-other"
    keep.write_text(FOREIGN, encoding="utf-8")
    res = run(sandbox, "uninstall.sh")
    assert res.returncode == 0, res.stderr
    assert not any((sandbox["bin"] / n).exists() for n in LAUNCHERS)
    assert keep.exists()


@needs_bash
def test_uninstall_force_removes_foreign_launcher(sandbox):
    foreign = sandbox["bin"] / "jira"
    foreign.write_text(FOREIGN, encoding="utf-8")
    res = run(sandbox, "uninstall.sh", "--force")
    assert res.returncode == 0, res.stderr
    assert not foreign.exists()


@needs_bash
def test_uninstall_treats_symlink_as_foreign(sandbox):
    target = sandbox["tmp"] / "real-jira"
    write_ours(target)
    link = sandbox["bin"] / "jira"
    link.symlink_to(target)
    res = run(sandbox, "uninstall.sh")
    assert res.returncode != 0
    assert link.is_symlink() and target.exists()


@needs_bash
@pytest.mark.parametrize("args", [(), ("--uninstall",)])
def test_install_refuses_foreign_launcher_before_doing_anything(sandbox, args):
    foreign = sandbox["bin"] / "jira-cli"
    foreign.write_text(FOREIGN, encoding="utf-8")
    cfg = sandbox["tmp"] / "cfg"
    res = run(sandbox, "install.sh", *args, config_dir=str(cfg))
    assert res.returncode != 0
    assert str(foreign) in res.stderr
    assert foreign.read_text(encoding="utf-8") == FOREIGN
    assert not sandbox["sentinel"].exists(), "install went on to create a virtualenv"
    assert not cfg.exists()


@needs_bash
def test_install_accepts_own_launchers_and_proceeds(sandbox):
    for name in LAUNCHERS:
        write_ours(sandbox["bin"] / name)
    res = run(sandbox, "install.sh", config_dir=str(sandbox["tmp"] / "cfg"))
    # Got past every safety check and reached virtualenv creation (fake python3).
    assert sandbox["sentinel"].exists(), res.stderr
    assert res.returncode != 0


@needs_bash
def test_install_force_proceeds_past_foreign_launcher(sandbox):
    (sandbox["bin"] / "jira").write_text(FOREIGN, encoding="utf-8")
    res = run(sandbox, "install.sh", "--force", config_dir=str(sandbox["tmp"] / "cfg"))
    assert sandbox["sentinel"].exists(), res.stderr
    assert "--force" in res.stderr


# --- JIRA_CONFIG_DIR validation -----------------------------------------------


def _bad_dirs(sb: dict) -> list[str]:
    home = str(sb["home"])
    return [
        "relative/dir",
        "/",
        home,
        home + "/",
        home + "/../evil",
        str(sb["tmp"]),
        "/etc",
        "/usr/local/x",
        "/tmp",  # noqa: S108 - asserted to be REFUSED as a config dir
    ]


@needs_bash
@pytest.mark.parametrize("script", ["install.sh", "uninstall.sh"])
def test_bad_config_dir_is_refused(sandbox, script):
    mode_before = sandbox["home"].stat().st_mode
    for bad in _bad_dirs(sandbox):
        res = run(sandbox, script, config_dir=bad)
        assert res.returncode != 0, bad
        assert "JIRA_CONFIG_DIR" in res.stderr, (bad, res.stderr)
        assert "rm -rf" not in res.stdout
    assert not sandbox["sentinel"].exists()
    assert sandbox["home"].stat().st_mode == mode_before, "home directory was chmodded"


@needs_bash
def test_install_refuses_populated_foreign_config_dir(sandbox):
    shared = sandbox["tmp"] / "shared"
    shared.mkdir()
    (shared / "notes.txt").write_text("x", encoding="utf-8")
    shared.chmod(0o755)
    res = run(sandbox, "install.sh", config_dir=str(shared))
    assert res.returncode != 0
    assert "does not look like a jira-cli config directory" in res.stderr
    assert (shared.stat().st_mode & 0o777) == 0o755
    assert not sandbox["sentinel"].exists()


@needs_bash
def test_install_accepts_existing_jira_config_dir(sandbox):
    cfg = sandbox["tmp"] / "cfg"
    cfg.mkdir()
    (cfg / "teams.yaml").write_text("teams: {}\n", encoding="utf-8")
    run(sandbox, "install.sh", config_dir=str(cfg))
    assert sandbox["sentinel"].exists()


@needs_bash
def test_uninstall_advice_quotes_paths_and_skips_foreign_config_dir(sandbox):
    cfg = sandbox["tmp"] / "odd dir"
    cfg.mkdir()
    res = run(sandbox, "uninstall.sh", config_dir=str(cfg))
    assert res.returncode == 0, res.stderr
    assert "holds no jira-cli files" in res.stdout
    assert f"rm -rf -- {cfg}" not in res.stdout
    (cfg / ".env").write_text("", encoding="utf-8")
    res = run(sandbox, "uninstall.sh", config_dir=str(cfg))
    assert "rm -rf -- " + str(cfg).replace(" ", "\\ ") in res.stdout


# --- launcher body quoting -------------------------------------------------------


def test_install_writes_launcher_with_quoted_target():
    text = (REPO / "install.sh").read_text(encoding="utf-8")
    assert 'printf \'exec %q "$@"\\n\' "$target"' in text
    assert 'exec "$target"' not in text
    assert MARKER in text
